#!/usr/bin/env node
// library-first: echo.functions.search → no existing impl found (2026-11-14)
/**
 * Vendors the @simplewebauthn/browser UMD bundle into a TypeScript module so
 * the owner console can inline it under a CSP nonce without reading
 * node_modules at runtime (which a bundled server build cannot rely on).
 *
 *   node scripts/vendor-webauthn-browser.mjs          rewrite the module
 *   node scripts/vendor-webauthn-browser.mjs --check  exit 1 when it is stale
 *
 * owner-console.test.ts fails when the vendored text differs from the
 * installed package, so a dependency bump cannot silently skip this step.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkgDir = join(root, "node_modules", "@simplewebauthn", "browser");
const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;
const bundle = readFileSync(join(pkgDir, "dist", "bundle", "index.umd.min.js"), "utf8").trim();

if (/<\/script|<!--/i.test(bundle)) {
  console.error("bundle contains a sequence that cannot be inlined in a <script> element");
  process.exit(1);
}

const sha256 = createHash("sha256").update(bundle, "utf8").digest("hex");
const out =
  "// library-first: echo.functions.search → no existing impl found (2026-11-14)\n" +
  "// GENERATED by scripts/vendor-webauthn-browser.mjs — do not edit. Third-party code:\n" +
  `// @simplewebauthn/browser ${version} (MIT), dist/bundle/index.umd.min.js, verbatim.\n` +
  `export const WEBAUTHN_BROWSER_VERSION = ${JSON.stringify(version)};\n` +
  `export const WEBAUTHN_BROWSER_SHA256 = ${JSON.stringify(sha256)};\n` +
  `export const WEBAUTHN_BROWSER_BUNDLE = ${JSON.stringify(bundle)};\n`;
const target = join(root, "src", "lib", "vault", "v2", "owner-console-webauthn-bundle.ts");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // missing = stale
  }
  if (current !== out) {
    console.error("owner-console-webauthn-bundle.ts is stale: run node scripts/vendor-webauthn-browser.mjs");
    process.exit(1);
  }
  console.log(`up to date (@simplewebauthn/browser ${version}, sha256 ${sha256})`);
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target} (@simplewebauthn/browser ${version}, sha256 ${sha256})`);
}
